/// =============================
/// MODELO TURNO
/// =============================
class Turno {
  final String codigo;
  final String descripcion;

  final double qMon;
  final double pSab;
  final double pDom;
  final double dRed;
  final double hEst;
  final double pTra;
  final double cPer;
  final double pNoc;
  final double hAdi;
  final double dCot;

  const Turno({
    required this.codigo,
    this.descripcion = "",
    this.qMon = 0.0,
    this.pSab = 0.0,
    this.pDom = 0.0,
    this.dRed = 0.0,
    this.hEst = 0.0,
    this.pTra = 0.0,
    this.cPer = 0.0,
    this.pNoc = 0.0,
    this.hAdi = 0.0,
    this.dCot = 0.0,
  });

  String get codigoVisible {
    final partes = codigo.split('-');

    if (partes.length != 2) return codigo;

    final numero = int.tryParse(partes[1]);

    if (numero == null) return codigo;

    final codigoFormateado = '${partes[0]}-$numero';

    if (descripcion.isNotEmpty) {
      return '$codigoFormateado [$descripcion]';
    }

    return codigoFormateado;
  }
}

